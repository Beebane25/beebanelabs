# STEP 4: Test Connections
# ============================================
def test_connections(env):
    print_step(4, "Test Koneksi")

    # Test Supabase
    print_info("Testing Supabase connection...")
    try:
        from urllib.request import Request, urlopen
        url = f"{env['supabase_url']}/rest/v1/users?select=id&limit=1"
        req = Request(url, headers={
            'apikey': env['supabase_anon'],
            'Authorization': f"Bearer {env['supabase_anon']}"
        })
        with urlopen(req, timeout=10) as resp:
            data = json.loads(resp.read().decode())
            print_ok(f"Supabase connected! Users table: {len(data)} rows")
    except Exception as e:
        print_err(f"Supabase connection failed: {e}")

    # Test Netlify Functions (if URL provided)
    netlify_url = get_input("\nNetlify Functions URL (kosongkan jika belum deploy)", "")
    if netlify_url:
        print_info("Testing Netlify Functions...")
        try:
            from urllib.request import Request, urlopen
            req = Request(f"{netlify_url}/.netlify/functions/auth", headers={'Content-Type': 'application/json'})
            with urlopen(req, timeout=10) as resp:
                print_ok(f"Netlify Functions connected!")
        except Exception as e:
            print_info(f"Netlify test: {e} (normal jika belum deploy)")

    return netlify_url


