import os
import json
import subprocess
import sys

PROJECT_DIR = os.path.dirname(os.path.abspath(__file__))

def print_header(text):
    print(f"\n{'='*50}")
    print(f"  {text}")
    print(f"{'='*50}")

def print_step(num, text):
    print(f"\n  [{num}] {text}")

def print_ok(text):
    print(f"  ✅ {text}")

def print_err(text):
    print(f"  ❌ {text}")

def print_info(text):
    print(f"  ℹ️  {text}")

def get_input(prompt, default=""):
    val = input(f"  {prompt}" + (f" [{default}]" if default else "") + ": ").strip()
    return val if val else default

# ============================================
# STEP 1: Setup Environment Variables
# ============================================
def setup_env():
    print_step(1, "Setup Environment Variables")

    env_file = os.path.join(PROJECT_DIR, '.env')

    if os.path.exists(env_file):
        print_info(".env file already exists")
        overwrite = get_input("Overwrite? (y/n)", "n")
        if overwrite.lower() != 'y':
            print_ok("Keeping existing .env")
            return

    print_info("Masukkan credentials dari Supabase & Midtrans:")
    print()

    supabase_url = get_input("Supabase URL", "https://xxxxx.supabase.co")
    supabase_anon = get_input("Supabase Anon Key", "")
    supabase_service = get_input("Supabase Service Key", "")
    midtrans_client = get_input("Midtrans Client Key", "YOUR_MIDTRANS_CLIENT_KEY")
    midtrans_server = get_input("Midtrans Server Key", "YOUR_MIDTRANS_SERVER_KEY")

    # Write .env file
    env_content = f"""# IoTHub Environment Variables
# Generated by setup.py

# Supabase
SUPABASE_URL={supabase_url}
SUPABASE_ANON_KEY={supabase_anon}
SUPABASE_SERVICE_KEY={supabase_service}

# Midtrans
MIDTRANS_CLIENT_KEY={midtrans_client}
MIDTRANS_SERVER_KEY={midtrans_server}
MIDTRANS_IS_PRODUCTION=false

# Netlify
SITE_NAME=iothub
"""

    with open(env_file, 'w') as f:
        f.write(env_content)

    print_ok(f"Created .env file")

    # Also create netlify environment
    netlify_env = os.path.join(PROJECT_DIR, '.env.production')
    with open(netlify_env, 'w') as f:
        f.write(env_content)

    print_ok("Created .env.production for Netlify")

    return {
        'supabase_url': supabase_url,
        'supabase_anon': supabase_anon,
        'supabase_service': supabase_service,
        'midtrans_client': midtrans_client,
        'midtrans_server': midtrans_server
    }


