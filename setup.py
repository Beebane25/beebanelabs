# STEP 2: Create Netlify Functions
# ============================================
def create_netlify_functions():
    print_step(2, "Create Netlify Functions")

    functions_dir = os.path.join(PROJECT_DIR, 'netlify', 'functions')

    # Create-supabase-auth function
    auth_code = '''
import json
import os
import hashlib
import secrets
import time
from urllib.request import Request, urlopen
from urllib.error import HTTPError

SUPABASE_URL = os.environ.get('SUPABASE_URL', '')
SUPABASE_KEY = os.environ.get('SUPABASE_SERVICE_KEY', '')

def supabase_request(endpoint, method='GET', data=None):
    url = f"{SUPABASE_URL}/rest/v1/{endpoint}"
    headers = {
        'apikey': SUPABASE_KEY,
        'Authorization': f'Bearer {SUPABASE_KEY}',
        'Content-Type': 'application/json',
        'Prefer': 'return=representation'
    }
    body = json.dumps(data).encode() if data else None
    req = Request(url, data=body, headers=headers, method=method)
    with urlopen(req, timeout=30) as resp:
        return json.loads(resp.read().decode())

def handler(event, context):
    if event['httpMethod'] == 'OPTIONS':
        return {"statusCode": 200, "headers": {"Access-Control-Allow-Origin": "*", "Access-Control-Allow-Headers": "Content-Type", "Access-Control-Allow-Methods": "POST, OPTIONS"}, "body": ""}

    if event['httpMethod'] != 'POST':
        return {"statusCode": 405, "body": json.dumps({"error": "Method not allowed"})}

    try:
        body = json.loads(event['body'])
        action = body.get('action', '')

        if action == 'register':
            email = body.get('email', '').strip()
            name = body.get('name', '').strip()
            password = body.get('password', '')

            if not email or not name or len(password) < 8:
                return {"statusCode": 400, "body": json.dumps({"error": "Data tidak valid. Password minimal 8 karakter."})}

            # Check if email exists
            existing = supabase_request(f"users?email=eq.{email}&select=id")
            if existing:
                return {"statusCode": 400, "body": json.dumps({"error": "Email sudah terdaftar"})}

            # Hash password with PBKDF2
            salt = secrets.token_hex(16)
            pw_hash = hashlib.pbkdf2_hmac('sha256', password.encode(), salt.encode(), 100000).hex()

            # Create user
            user = supabase_request("users", "POST", {
                "email": email, "name": name, "password_hash": f"{salt}:{pw_hash}",
                "plan": "free", "is_active": True
            })

            if user:
                token = secrets.token_hex(32)
                supabase_request("sessions", "POST", {
                    "user_id": user[0]['id'], "token": token,
                    "expires_at": time.strftime("%Y-%m-%dT%H:%M:%S+00:00", time.gmtime(time.time()+86400))
                })
                return {"statusCode": 200, "headers": {"Access-Control-Allow-Origin": "*"}, "body": json.dumps({
                    "success": True, "token": token,
                    "user": {"email": email, "name": name, "plan": "free"}
                })}

            return {"statusCode": 500, "body": json.dumps({"error": "Gagal membuat akun"})}

        elif action == 'login':
            email = body.get('email', '').strip()
            password = body.get('password', '')

            users = supabase_request(f"users?email=eq.{email}&select=id,email,name,password_hash,plan")
            if not users:
                return {"statusCode": 401, "body": json.dumps({"error": "Email atau password salah"})}

            user = users[0]
            stored = user['password_hash']
            salt, pw_hash = stored.split(':')

            check = hashlib.pbkdf2_hmac('sha256', password.encode(), salt.encode(), 100000).hex()
            if check != pw_hash:
                return {"statusCode": 401, "body": json.dumps({"error": "Email atau password salah"})}

            token = secrets.token_hex(32)
            supabase_request("sessions", "POST", {
                "user_id": user['id'], "token": token,
                "expires_at": time.strftime("%Y-%m-%dT%H:%M:%S+00:00", time.gmtime(time.time()+86400))
            })

            supabase_request("users?email=eq." + email, "PATCH", {
                "last_login": time.strftime("%Y-%m-%dT%H:%M:%S+00:00", time.gmtime())
            })

            return {"statusCode": 200, "headers": {"Access-Control-Allow-Origin": "*"}, "body": json.dumps({
                "success": True, "token": token,
                "user": {"email": email, "name": user['name'], "plan": user['plan']}
            })}

        return {"statusCode": 400, "body": json.dumps({"error": "Invalid action"})}

    except Exception as e:
        print(f"Error: {str(e)}")
        return {"statusCode": 500, "body": json.dumps({"error": "Internal server error"})}
'''

    os.makedirs(functions_dir, exist_ok=True)

    with open(os.path.join(functions_dir, 'auth.py'), 'w') as f:
        f.write(auth_code)
    print_ok("Created netlify/functions/auth.py")

    return True


