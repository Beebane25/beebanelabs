# STEP 3: Update Frontend API URL
# ============================================
def update_frontend_api_url(netlify_url):
    print_step(3, "Update Frontend API URL")

    # Update pricing.html
    pricing_path = os.path.join(PROJECT_DIR, 'pricing.html')
    if os.path.exists(pricing_path):
        with open(pricing_path, 'r', encoding='utf-8') as f:
            content = f.read()

        # Replace API_BASE
        content = content.replace(
            "const API_BASE = 'https://beebane25.iothub-api.netlify.app'",
            f"const API_BASE = '{netlify_url}'"
        )

        with open(pricing_path, 'w', encoding='utf-8') as f:
            f.write(content)
        print_ok(f"Updated pricing.html → {netlify_url}")

    # Update js/app.js
    appjs_path = os.path.join(PROJECT_DIR, 'js', 'app.js')
    if os.path.exists(appjs_path):
        with open(appjs_path, 'r', encoding='utf-8') as f:
            content = f.read()

        content = content.replace(
            "API_BASE: 'https://beebane25.iothub-api.netlify.app'",
            f"API_BASE: '{netlify_url}'"
        )

        with open(appjs_path, 'w', encoding='utf-8') as f:
            f.write(content)
        print_ok(f"Updated js/app.js → {netlify_url}")


